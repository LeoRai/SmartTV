-- 1 враг, 2 врага, 5 врагов, 21 враг
function ns.Plural(n, forms)
    local m10, m100 = n % 10, n % 100
    if m10 == 1 and m100 ~= 11 then return forms[1] end
    if m10 >= 2 and m10 <= 4 and (m100 < 12 or m100 > 14) then return forms[2] end
    return forms[3]
end

